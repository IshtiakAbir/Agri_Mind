print("🏗️ Building EfficientNetB3 transfer-learning model...")

data_augmentation = tf.keras.Sequential([
    layers.RandomFlip(mode="horizontal_and_vertical"),
    layers.RandomRotation(factor=0.2),
    layers.RandomZoom(0.15),
    layers.RandomContrast(0.15),
    layers.RandomTranslation(0.1, 0.1),
], name="data_augmentation")

base_model = EfficientNetB3(
    include_top=False,
    weights="imagenet",
    input_shape=(IMAGE_SIZE, IMAGE_SIZE, 3),
    pooling=None
)
base_model.trainable = False  # Phase 1: freeze backbone, train only the new head

inputs = tf.keras.Input(shape=(IMAGE_SIZE, IMAGE_SIZE, 3))
x = data_augmentation(inputs)
x = preprocess_input(x)
x = base_model(x, training=False)
x = layers.GlobalAveragePooling2D()(x)
x = layers.BatchNormalization()(x)
x = layers.Dropout(0.4)(x)
# IMPROVEMENT: an extra wider dense block gives the head more room to combine
# EfficientNetB3's 1536-dim features before collapsing to the class logits.
# BatchNorm + L2 + Dropout keep it from just overfitting on that extra capacity.
x = layers.Dense(512, activation='relu', kernel_regularizer=tf.keras.regularizers.l2(1e-4))(x)
x = layers.BatchNormalization()(x)
x = layers.Dropout(0.4)(x)
x = layers.Dense(256, activation='relu', kernel_regularizer=tf.keras.regularizers.l2(1e-4))(x)
x = layers.Dropout(0.3)(x)
# Output layer stays float32 even under mixed precision, for numerical stability
outputs = layers.Dense(len(class_names), activation='softmax', dtype='float32')(x)

CNN = models.Model(inputs, outputs, name="EfficientNetB3_Poultry")

# IMPROVEMENT: label smoothing.
# SparseCategoricalCrossentropy doesn't expose label_smoothing, so we wrap it:
# one-hot the sparse integer label internally, then delegate to
# CategoricalCrossentropy(label_smoothing=...). This is a drop-in loss that
# still consumes the SAME sparse-int-label datasets the rest of the notebook
# already builds/evaluates with - no changes needed anywhere else.
# Why it helps push toward 98%: with only a few disease classes and a
# pretrained backbone, the model can become over-confident on training data
# (softmax pushed to ~0/1) which hurts generalization to the held-out test
# set. Smoothing the targets slightly (0.9 / 0.1 instead of 1.0 / 0.0) keeps
# gradients from over-fitting samples the model has already "solved",
# typically buying a small but real bump in test accuracy and better-calibrated
# confidences.
NUM_CLASSES = len(class_names)

def label_smoothed_loss(y_true, y_pred, label_smoothing=0.1, num_classes=NUM_CLASSES):
    y_true_oh = tf.one_hot(tf.cast(y_true, tf.int32), depth=num_classes)
    return tf.keras.losses.categorical_crossentropy(
        y_true_oh, y_pred, label_smoothing=label_smoothing
    )

CNN.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=1e-3),
    loss=label_smoothed_loss,
    metrics=['accuracy']
)

print("✅ Model built and compiled successfully!")

# 5. TEST-TIME AUGMENTATION (TTA)
def tta_predict(model, images, n_aug=4):
    preds = model.predict(images, verbose=0)
    preds_flip = model.predict(tf.image.flip_left_right(images), verbose=0)
    avg = (preds + preds_flip) / 2.0
    if n_aug >= 4:
        preds_bright_up = model.predict(tf.image.adjust_brightness(images, 0.05), verbose=0)
        preds_bright_down = model.predict(tf.image.adjust_brightness(images, -0.05), verbose=0)
        avg = (avg * 2 + preds_bright_up + preds_bright_down) / 4.0
    return avg

print("\n🔁 Re-scoring the test set with Test-Time Augmentation (avg over flips/brightness)...")

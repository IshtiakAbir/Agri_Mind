# IMPROVEMENT: patience bumped 5 -> 7. With more fine-tuning epochs and a
# cosine-decay schedule (below) the val_loss curve can plateau for a few
# epochs before the smaller LR steps start paying off again - stopping too
# early throws away those later gains.
early_stopping = EarlyStopping(
    monitor='val_loss',
    patience=7,
    restore_best_weights=True
)

checkpoint_callback = ModelCheckpoint(
    filepath=os.path.join(backup_folder, "poultry_disease_model_best.keras"),
    monitor="val_accuracy",
    save_best_only=True,
    verbose=1
)

# NOTE: ReduceLROnPlateau directly overwrites optimizer.learning_rate, which
# only works when the optimizer was built with a plain float learning rate.
# Phase 1's optimizer (Adam(1e-3), set back in Block 2) is a plain float, so
# it's used there. Phase 2's optimizer is rebuilt with a CosineDecay
# schedule (below), and schedule-based learning rates are NOT settable -
# combining the two raises:
#   TypeError: This optimizer was created with a `LearningRateSchedule`...
# So we keep two callback lists: Phase 1 keeps reduce_lr, Phase 2 drops it
# (the cosine schedule already handles annealing the LR down, so it's
# redundant there anyway).
reduce_lr = ReduceLROnPlateau(
    monitor='val_loss',
    factor=0.3,
    patience=2,
    min_lr=1e-7,
    verbose=1
)

callbacks_phase1 = [early_stopping, checkpoint_callback, reduce_lr]
callbacks_phase2 = [early_stopping, checkpoint_callback]

# IMPROVEMENT: phase 1 epochs 15 -> 20. The head (freshly-initialized Dense
# layers) needs enough epochs to actually converge before we start touching
# the pretrained backbone weights in phase 2; EarlyStopping still cuts it
# short if it converges sooner, so this only helps, never hurts runtime.
PHASE1_EPOCHS = 20

print("\n🚀 PHASE 1: Training classification head (backbone frozen)...")
training_his = CNN.fit(
    train_ds,
    validation_data=val_ds,
    epochs=PHASE1_EPOCHS,
    class_weight=class_weight_dict,
    callbacks=callbacks_phase1
)

print("\n🔧 PHASE 2: Fine-tuning top layers of EfficientNetB3...")
# IMPROVEMENT: unfreeze the top 50% of the backbone instead of top 30%.
# More of the backbone gets to specialize on fecal-image disease texture
# instead of staying generic ImageNet features - this is the single biggest
# lever for closing the last few points to ~98%, since it lets mid-level
# filters (not just the very last block) adapt to this specific domain.
base_model.trainable = True
fine_tune_at = int(len(base_model.layers) * 0.5)
for layer in base_model.layers[:fine_tune_at]:
    layer.trainable = False

FINE_TUNE_EPOCHS = 30
steps_per_epoch = tf.data.experimental.cardinality(train_ds).numpy()

# IMPROVEMENT: cosine-decay LR schedule instead of a flat 1e-5.
# A constant fine-tuning LR either wastes early epochs (too small) or
# destabilizes late epochs (too large for the last mile). Cosine decay starts
# at a slightly higher 3e-5, giving the newly-unfrozen mid-layers a real
# chance to move, then smoothly anneals toward ~0 so the last few epochs are
# fine, precise updates - exactly what's needed to squeeze out the last
# couple of accuracy points.
lr_schedule = tf.keras.optimizers.schedules.CosineDecay(
    initial_learning_rate=3e-5,
    decay_steps=steps_per_epoch * FINE_TUNE_EPOCHS,
    alpha=0.01  # decays down to ~1% of the initial LR, not all the way to 0
)

# IMPROVEMENT: AdamW (decoupled weight decay) instead of plain Adam for the
# fine-tuning phase - extra regularization specifically while the backbone
# weights are unfrozen and most at risk of overfitting the (relatively) small
# poultry dataset.
CNN.compile(
    optimizer=tf.keras.optimizers.AdamW(learning_rate=lr_schedule, weight_decay=1e-5),
    loss=label_smoothed_loss,
    metrics=['accuracy']
)

total_epochs = training_his.epoch[-1] + 1 + FINE_TUNE_EPOCHS

training_his_fine = CNN.fit(
    train_ds,
    validation_data=val_ds,
    epochs=total_epochs,
    initial_epoch=training_his.epoch[-1] + 1,
    class_weight=class_weight_dict,
    callbacks=callbacks_phase2
)

